import test from 'node:test';
import assert from 'node:assert/strict';

import {
  listCatalogItems,
} from '../src/catalog.js';
import { planAutomaticDepot } from '../src/autoDepot.js';
import {
  MODULE_CONTRACT_PROFILES,
  hasExplicitModuleContract,
  resolveModuleContract,
} from '../src/moduleContracts.js';
import { getCommercialItemForType, getItem } from '../src/items.js';
import { composeAutomaticStandWall } from '../src/automaticWall.js';
import { FEATURE_CONTRACTS, getFeatureContract } from '../src/featureContracts.js';
import { planAutomaticFascia } from '../src/autoFascia.js';
import { AUTO_FURNITURE_ITEM_KEYS, planAutomaticFurniture } from '../src/autoFurniture.js';
import { readFileSync } from 'node:fs';

const REQUIRED_CONTRACT_SECTIONS = Object.freeze([
  'state',
  'appearance',
  'renderer',
  'runtime',
  'composition',
  'bom',
  'tests',
  'behavior',
]);

test('every catalog item resolves a module contract from type (no per-SKU allowlist)', () => {
  const missing = listCatalogItems().map((item) => item.itemKey).filter((moduleKey) => !hasExplicitModuleContract(moduleKey));

  assert.deepEqual(missing, [], `Catalog items missing module contract: ${missing.join(', ')}`);
});

test('every catalog module contract resolves all required policy sections', () => {
  for (const moduleKey of listCatalogItems().map((item) => item.itemKey)) {
    const contract = resolveModuleContract(moduleKey);
    assert.ok(contract, `Module contract did not resolve: ${moduleKey}`);
    assert.ok(MODULE_CONTRACT_PROFILES[contract.profile], `Unknown profile for ${moduleKey}: ${contract.profile}`);

    for (const section of REQUIRED_CONTRACT_SECTIONS) {
      assert.ok(contract[section], `${moduleKey} contract is missing ${section}`);
    }

    assert.ok(contract.state.owner, `${moduleKey} state owner is missing`);
    assert.ok(contract.state.persistence, `${moduleKey} persistence policy is missing`);
    assert.ok(contract.appearance.color, `${moduleKey} color policy is missing`);
    assert.ok(contract.appearance.image, `${moduleKey} image policy is missing`);
    assert.ok(contract.renderer.mode, `${moduleKey} renderer policy is missing`);
    assert.ok(contract.runtime.mode, `${moduleKey} runtime policy is missing`);
    assert.ok(contract.composition.mode, `${moduleKey} composition policy is missing`);
    assert.ok(contract.bom.mode, `${moduleKey} BOM policy is missing`);
    assert.equal(contract.tests.contract, 'required', `${moduleKey} must require contract tests`);

    assert.ok(contract.behavior.placement, `${moduleKey} placement behavior is missing`);
    assert.ok(Number.isFinite(Number(contract.behavior.moveSnapCm)), `${moduleKey} move snap is missing`);
    assert.ok(Number.isFinite(Number(getItem(moduleKey).rotationStepDeg)), `${moduleKey} rotation step is missing`);
    assert.ok(contract.behavior.collision, `${moduleKey} collision behavior is missing`);
  }
});

test('recipe-backed module contracts resolve an actual canonical recipe', () => {
  for (const moduleKey of listCatalogItems().map((item) => item.itemKey)) {
    const contract = resolveModuleContract(moduleKey);
    if (contract?.bom?.mode !== 'recipe') continue;

    const item = getItem(moduleKey);
    assert.ok(
      Array.isArray(item.composition?.items) && item.composition.items.length > 0,
      `${moduleKey} declares recipe BOM but composition.items is missing`,
    );
  }
});

test('non-catalog runtime modules can also have explicit contracts', () => {
  const contract = resolveModuleContract('illuminated-foam');
  assert.ok(contract);
  assert.equal(contract.itemKey, 'illuminated-foam');
  assert.equal(contract.behavior.placement, 'wall-overlay');
  assert.equal(contract.appearance.image, 'required');
});

test('automatic depot feature contract matches the contents generated by the planner', () => {
  const contract = FEATURE_CONTRACTS.automaticDepot;
  assert.equal(getFeatureContract('automatic-depot'), contract);

  const plan = planAutomaticDepot({
    standType: 'island',
    standXCm: 600,
    standYCm: 500,
    sizeKey: '200x200',
    includeContents: true,
  });

  assert.equal(plan.ok, true);
  const generatedContentKinds = plan.specs
    .map((spec) => spec.kind)
    .filter((kind) => contract.creates.contentKinds.includes(kind))
    .sort();

  assert.deepEqual(generatedContentKinds, [...contract.creates.contentKinds].sort());
  assert.equal(contract.trigger.contentToggle, 'includeContents');

  const expectedCatalogKeys = contract.creates.contentKinds.map((kind) => {
    const item = getCommercialItemForType(kind);
    assert.ok(item, `contentKinds ${kind} must resolve a commercial Item`);
    return item.itemKey;
  });
  assert.deepEqual([...contract.creates.contentCatalogKeys], expectedCatalogKeys);
  assert.match(contract.tests.regressionFiles.join(' '), /test\/autoDepot\.test\.js/);
});

test('automatic wall feature contract matches composeAutomaticStandWall', () => {
  const contract = FEATURE_CONTRACTS.automaticWall;
  assert.equal(getFeatureContract('automatic-wall'), contract);
  assert.equal(contract.owner, 'src/automaticWall.js');
  assert.equal(contract.trigger.mode, 'non-island-stage-create');
  assert.deepEqual([...contract.inputs], ['wallWidthCm', 'standType', 'standXCm', 'standYCm']);
  assert.deepEqual([...contract.creates.structuralKinds], ['flat-panel']);
  assert.deepEqual([...contract.creates.lightingKinds], ['led-floodlight']);
  assert.equal(contract.placement.owner, 'src/wallReflow.js');
  assert.match(contract.tests.regressionFiles.join(' '), /automaticWall\.test\.js/);

  const result = composeAutomaticStandWall({
    wallWidthCm: 900,
    standType: 'l-left',
    standXCm: 500,
    standYCm: 400,
  });
  assert.equal(result.ok, true);
  assert.deepEqual(result.widths, [200, 200, 200, 200, 100]);
});

test('automatic fascia feature contract matches planAutomaticFascia', () => {
  const contract = FEATURE_CONTRACTS.automaticFascia;
  assert.equal(getFeatureContract('automatic-fascia'), contract);
  assert.equal(contract.owner, 'src/autoFascia.js');
  assert.deepEqual([...contract.inputs], ['standType', 'standXCm', 'standYCm', 'rows']);
  assert.match(contract.tests.regressionFiles.join(' '), /autoFascia\.test\.js/);

  for (const rows of [1, 2]) {
    const plan = planAutomaticFascia({ standType: 'island', standXCm: 400, standYCm: 300, rows });
    assert.equal(plan.ok, true);
    assert.ok(contract.creates.panelVariants.includes(plan.variant));
  }
});

test('automatic furniture feature contract matches planAutomaticFurniture', () => {
  const contract = FEATURE_CONTRACTS.automaticFurniture;
  assert.equal(getFeatureContract('automatic-furniture'), contract);
  assert.equal(contract.owner, 'src/autoFurniture.js');
  assert.equal(contract.trigger.defaultEnabled, true);
  assert.deepEqual([...contract.inputs], ['standXCm', 'standYCm', 'depot']);
  assert.deepEqual([...contract.creates.furnitureCatalogKeys].sort(), Object.values(AUTO_FURNITURE_ITEM_KEYS).sort());
  assert.match(contract.tests.regressionFiles.join(' '), /autoFurniture.test.js/);

  const plan = planAutomaticFurniture({ standXCm: 600, standYCm: 300 });
  assert.equal(plan.ok, true);
  assert.deepEqual(plan.specs.map((spec) => spec.itemKey).sort(), [...contract.creates.furnitureCatalogKeys].sort());
});

test('moduleContracts and featureContracts stay governance-only: production runtime does not import them', () => {
  const runtimeFiles = [
    'src/main.js',
    'src/itemBom.js',
    'src/moduleBehavior.js',
    'src/autoDepot.js',
    'src/autoFascia.js',
    'src/autoFurniture.js',
    'src/automaticWall.js',
    'src/scene3d.js',
    'src/designState.js',
  ];
  for (const relative of runtimeFiles) {
    const source = readFileSync(new URL(`../${relative}`, import.meta.url), 'utf8');
    assert.doesNotMatch(source, /from '\.\/moduleContracts\.js'/, relative);
    assert.doesNotMatch(source, /from '\.\/featureContracts\.js'/, relative);
  }
});
