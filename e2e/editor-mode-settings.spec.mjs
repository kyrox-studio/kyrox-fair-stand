import { test, expect } from '@playwright/test';

test('Ayarlar, gruplar, şablonlar ve standartlar yalnız Gelişmiş modda görünür; tercih korunur', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const selector = page.getByRole('group', { name: 'Düzenleme modu', exact: true });
  await expect(selector).toHaveCount(1);
  const simple = selector.getByRole('button', { name: 'Basit', exact: true });
  const advanced = selector.getByRole('button', { name: 'Gelişmiş', exact: true });
  const settings = page.locator('details.editor-settings-card');
  const advancedPanels = [settings, page.locator('#module-groups-card'), page.locator('#module-templates-card'), page.locator('#stand-standards-card')];
  await expect(simple).toHaveAttribute('aria-pressed', 'true');
  for (const panel of advancedPanels) await expect(panel).toBeHidden();
  await advanced.click();
  for (const panel of advancedPanels) await expect(panel).toBeVisible();
  await settings.locator('summary').click();
  const measurements = page.getByRole('checkbox', { name: 'Ölçüleri göster', exact: true });
  await expect(measurements).toBeChecked();
  await measurements.uncheck();
  await page.locator('#autosave-interval').selectOption('5');
  await simple.click();
  for (const panel of advancedPanels) await expect(panel).toBeHidden();
  await advanced.click();
  await expect(measurements).not.toBeChecked();
  await expect(page.locator('#autosave-interval')).toHaveValue('5');
  const project = page.locator('details.project-card');
  await project.locator('summary').click();
  await expect(project).not.toHaveAttribute('open', '');
  await expect(settings).toHaveAttribute('open', '');
  await settings.locator('summary').focus();
  await page.keyboard.press('Enter');
  await expect(settings).not.toHaveAttribute('open', '');
  await page.keyboard.press('Enter');
  await expect(settings).toHaveAttribute('open', '');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(selector).toBeVisible();
  await page.screenshot({ path: 'test-results/editor-mode-sidebar.png' });
  await page.reload();
  await expect(simple).toHaveAttribute('aria-pressed', 'true');
  await expect(settings).toBeHidden();
  await advanced.click();
  await settings.locator('summary').click();
  await expect(measurements).toBeChecked();
  expect(errors).toEqual([]);
});
